"""Local demo: write the wall config, host launcher and Native Messaging host manifest
in a throwaway Chrome profile. Windows registers the demo-specific manifest in
the selected browser's per-user registry key.

Reuses the U09 installer's host name, description and manifest shape (bridge/install.py),
but targets a custom directory and a launcher that runs `python -m bridge.wall host
--config <demo config>` with cwd = repo. The U09 launcher puts only bridge/ on sys.path,
so `bridge.wall.room_relay` (which imports `bridge.room.store`) cannot load there and the
room relay would stay off.

  python3 tools/demo/setup_native.py --profile DIR --ext-id ID --cw-home DIR --config-out FILE
                                     [--room demo [--room viewpoint ...]] [--tier private] [--log FILE]
--room may repeat: every named room goes into rooms.allow with the same tier (default: demo).
Refuses any target under ~/.config (never touches a real Chrome profile).
"""
import argparse
import json
import os
import shlex
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))
from bridge import install  # noqa: E402  (HOST_NAME, DESCRIPTION, _valid_id)


def _demo_registry_key(browser, host):
    return install._registry_subkey(browser).removesuffix(install.HOST_NAME) + host


def register_windows_host(browser, host, manifest):
    wr = install._get_winreg()
    with wr.CreateKey(wr.HKEY_CURRENT_USER, _demo_registry_key(browser, host)) as key:
        try:
            value, _ = wr.QueryValueEx(key, "")
        except FileNotFoundError:
            value = str(manifest)
        if value != str(manifest):
            raise ValueError("demo host is already registered to another profile")
        wr.SetValueEx(key, "", 0, wr.REG_SZ, str(manifest))


def unregister_windows_host(browser, manifest):
    prefix = install.HOST_NAME + ".demo."
    host = manifest.stem
    if not host.startswith(prefix) or not install._valid_id(host.removeprefix(prefix)):
        raise ValueError("invalid demo host manifest name")
    wr = install._get_winreg()
    subkey = _demo_registry_key(browser, host)
    try:
        with wr.OpenKey(wr.HKEY_CURRENT_USER, subkey) as key:
            value, _ = wr.QueryValueEx(key, "")
        if value == str(manifest):
            wr.DeleteKey(wr.HKEY_CURRENT_USER, subkey)
    except FileNotFoundError:
        pass


def _cmd_quote(value):
    # CMD expands percent signs even inside quotes. Delayed expansion is off.
    return '"' + str(value).replace("%", "%%") + '"'


def write_launcher(launcher, cw_home, cfg_path, log, windows):
    if windows:
        # Chrome supplies the extension origin first, then its window handle.
        launcher.write_text(
            "@echo off\n"
            "setlocal DisableDelayedExpansion\n"
            "chcp 65001 >nul\n"
            "pushd " + _cmd_quote(REPO) + " || exit /b 1\n"
            "set " + _cmd_quote("CW_HOME=" + str(cw_home)) + "\n"
            "set " + _cmd_quote("PYTHONPATH=" + str(REPO)) + "\n"
            "set PYTHONDONTWRITEBYTECODE=1\n"
            + _cmd_quote(sys.executable) + " -m bridge.wall host --config "
            + _cmd_quote(cfg_path) + " %1 2>> " + _cmd_quote(log) + "\n",
            encoding="utf-8", newline="\r\n")
        return
    launcher.write_text(
        "#!/bin/sh\n"
        "# Context Wall demo native host launcher (generated by tools/demo/setup_native.py).\n"
        "cd " + shlex.quote(str(REPO)) + " || exit 1\n"
        "export CW_HOME=" + shlex.quote(str(cw_home)) + "\n"
        "export PYTHONPATH=" + shlex.quote(str(REPO)) + "\n"
        "export PYTHONDONTWRITEBYTECODE=1\n"
        "echo \"$(date +%s) spawn pid=$$ args=$*\" >> " + shlex.quote(log) + "\n"
        "exec " + shlex.quote(sys.executable) + " -m bridge.wall host --config "
        + shlex.quote(str(cfg_path)) + " \"$@\" 2>> " + shlex.quote(log) + "\n",
        encoding="utf-8")
    os.chmod(launcher, 0o755)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--profile")
    ap.add_argument("--ext-id")
    ap.add_argument("--cw-home")
    ap.add_argument("--config-out")
    ap.add_argument("--room", action="append", default=None)
    ap.add_argument("--tier", default="private", choices=("private", "standard"))
    ap.add_argument("--agent", default="wall-user")
    ap.add_argument("--log", default=None)
    ap.add_argument("--browser", choices=install.BROWSERS, default="chrome")
    ap.add_argument("--unregister", type=Path)
    a = ap.parse_args(argv)
    windows = sys.platform == "win32"
    if a.unregister is not None:
        if windows:
            unregister_windows_host(a.browser, a.unregister.resolve())
        return 0
    if not all((a.profile, a.ext_id, a.cw_home, a.config_out)):
        ap.error("--profile, --ext-id, --cw-home and --config-out are required")

    if not install._valid_id(a.ext_id):
        print("bad extension id", file=sys.stderr)
        return 2
    profile = Path(a.profile).resolve()
    protected = [(Path.home() / ".config").resolve()]
    if windows:
        local = Path(os.environ.get("LOCALAPPDATA") or Path.home() / "AppData" / "Local")
        protected.extend(local.joinpath(*vendor.split("\\"), "User Data").resolve()
                         for vendor in install._VENDOR_PATHS.values())
    else:
        protected.extend(install._manifest_dir(browser).parent.resolve()
                         for browser in install.BROWSERS)
    if any(profile == root or root in profile.parents for root in protected):
        print("refusing a real browser profile", file=sys.stderr)
        return 2

    rooms = list(dict.fromkeys(a.room or ["demo"]))  # de-duplicated, order kept
    cw_home = Path(a.cw_home).resolve()
    cfg_path = Path(a.config_out).resolve()
    spool = cfg_path.parent / "spool"
    spool.mkdir(parents=True, exist_ok=True)
    cw_home.mkdir(parents=True, exist_ok=True)
    cfg = {
        "v": 1,
        "extensionId": a.ext_id,
        "spoolDir": str(spool),
        "projects": [],
        "rooms": {
            "allow": [{"room": r, "tier": a.tier} for r in rooms],
            "agent": a.agent,
            "home": str(cw_home),
        },
    }
    cfg_path.write_text(json.dumps(cfg, indent=2) + "\n", encoding="utf-8")

    nmh = profile / "NativeMessagingHosts"
    nmh.mkdir(parents=True, exist_ok=True)
    host = install.HOST_NAME + ".demo." + a.ext_id if windows else install.HOST_NAME
    launcher = nmh / (host + (".host.cmd" if windows else ".host.sh"))
    log = str(Path(a.log).resolve()) if a.log else str(cfg_path.parent / "logs" / "native_host.stderr.log")
    Path(log).parent.mkdir(parents=True, exist_ok=True)
    write_launcher(launcher, cw_home, cfg_path, log, windows)
    manifest = {
        "name": host,
        "description": install.DESCRIPTION,
        "path": str(launcher),
        "type": "stdio",
        "allowed_origins": ["chrome-extension://" + a.ext_id + "/"],
    }
    mpath = nmh / (host + ".json")
    mpath.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    if windows:
        register_windows_host(a.browser, host, mpath)
    print(json.dumps({"ok": True, "manifest": str(mpath), "launcher": str(launcher),
                      "config": str(cfg_path)}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
